"""Rebuild all m-agent branding assets from the original Scribbles drawing (PRD-08).

Input:  assets/branding/scribbles/scribbles-original.png (white strokes on transparency)
Output: Scribbles as PNG/SVG in black and white, the m-agent logo (M + Scribbles) as
        SVG/PNG/ICO, the KoboldCpp icon files niko.ico / nikogreen.ico and the Discord
        profile picture discord-avatar.png (white Scribbles on dark, 512 x 512).

Developer tool only (not part of the runtime):
    pip install pillow numpy potracer cairosvg
    python scripts/build_branding.py
"""

from __future__ import annotations

from pathlib import Path

import cairosvg
import numpy as np
import potrace
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
BRANDING = ROOT / "assets" / "branding"
SCRIBBLES = BRANDING / "scribbles"
ORIGINAL = SCRIBBLES / "scribbles-original.png"

ALPHA_THRESHOLD = 100  # strokes are opaque; the canvas carries faint alpha noise (1-3)
PADDING = 8
ICO_SIZES = [(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]

# Logo geometry on a 512 x 512 canvas.
M_POINTS = "44,402 44,142 104,142 158,258 212,142 272,142 272,402 220,402 220,238 172,336 144,336 96,238 96,402"
SCRIBBLES_HEIGHT = 300.0
SCRIBBLES_RIGHT = 478.0
SCRIBBLES_TOP = 102.0
SCRIBBLES_LOGO_STROKE = 12.0  # thickens the thin pen lines so Scribbles survives small icon sizes


def stroke_mask() -> np.ndarray:
    alpha = np.array(Image.open(ORIGINAL).convert("RGBA").getchannel("A"))
    mask = alpha > ALPHA_THRESHOLD
    ys, xs = np.where(mask)
    y0, y1 = max(ys.min() - PADDING, 0), ys.max() + PADDING + 1
    x0, x1 = max(xs.min() - PADDING, 0), xs.max() + PADDING + 1
    return mask[y0:y1, x0:x1]


def trace(mask: np.ndarray) -> str:
    # potracer traces "dark" pixels, i.e. False values, so the stroke mask is inverted.
    curves = potrace.Bitmap(~mask).trace(
        turdsize=20, alphamax=1.0, opticurve=True, opttolerance=0.2
    )

    def num(value: float) -> str:
        return f"{value:.1f}"

    paths = []
    for curve in curves:
        start = curve.start_point
        parts = [f"M{num(start.x)} {num(start.y)}"]
        for seg in curve.segments:
            end = seg.end_point
            if seg.is_corner:
                parts.append(f"L{num(seg.c.x)} {num(seg.c.y)}L{num(end.x)} {num(end.y)}")
            else:
                parts.append(
                    f"C{num(seg.c1.x)} {num(seg.c1.y)} {num(seg.c2.x)} {num(seg.c2.y)} "
                    f"{num(end.x)} {num(end.y)}"
                )
        parts.append("Z")
        paths.append("".join(parts))
    return " ".join(paths)


def scribbles_svg(width: int, height: int, path: str, fill: str) -> str:
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}" role="img" aria-label="Scribbles">
  <title>Scribbles – Maskottchen von LayerNX und moritz-agent</title>
  <path fill="{fill}" fill-rule="evenodd" d="{path}"/>
</svg>
"""


def logo_svg(width: int, height: int, path: str) -> str:
    scale = SCRIBBLES_HEIGHT / height
    left = SCRIBBLES_RIGHT - width * scale
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="m-agent logo">
  <title>m-agent</title>
  <!-- Monochrome mark: bold "M" with Scribbles, the LayerNX mascot. Generated by scripts/build_branding.py -->
  <rect x="0" y="0" width="512" height="512" rx="96" fill="#ffffff"/>
  <rect x="12" y="12" width="488" height="488" rx="86" fill="none" stroke="#000000" stroke-width="16"/>
  <polygon fill="#000000" points="{M_POINTS}"/>
  <g transform="translate({left:.2f} {SCRIBBLES_TOP:.2f}) scale({scale:.5f})">
    <path fill="#000000" fill-rule="evenodd" stroke="#000000" stroke-width="{SCRIBBLES_LOGO_STROKE}" stroke-linejoin="round" d="{path}"/>
  </g>
</svg>
"""


def avatar_svg(width: int, height: int, path: str) -> str:
    """Discord profile picture: white Scribbles centred on a dark square (Discord crops it round)."""
    size = 512.0
    scale = size * 0.62 / max(width, height)
    left = (size - width * scale) / 2
    top = (size - height * scale) / 2
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="Anton">
  <title>Anton</title>
  <rect x="0" y="0" width="512" height="512" fill="#1b1b1f"/>
  <g transform="translate({left:.2f} {top:.2f}) scale({scale:.5f})">
    <path fill="#ffffff" fill-rule="evenodd" stroke="#ffffff" stroke-width="{SCRIBBLES_LOGO_STROKE / scale * 0.5:.2f}" stroke-linejoin="round" d="{path}"/>
  </g>
</svg>
"""


def render(svg: Path, png: Path, width: int, height: int | None = None) -> None:
    cairosvg.svg2png(url=str(svg), write_to=str(png), output_width=width, output_height=height)


def main() -> None:
    mask = stroke_mask()
    height, width = mask.shape
    path = trace(mask)

    for name, fill in (("black", "#000000"), ("white", "#ffffff")):
        svg = SCRIBBLES / f"scribbles-{name}.svg"
        svg.write_text(scribbles_svg(width, height, path, fill), encoding="utf-8")
        render(svg, SCRIBBLES / f"scribbles-{name}-512.png", int(512 * width / height), 512)

    logo = BRANDING / "m-agent-logo.svg"
    logo.write_text(logo_svg(width, height, path), encoding="utf-8")
    for size in (512, 192, 64):
        render(logo, BRANDING / f"m-agent-logo-{size}.png", size, size)

    avatar = BRANDING / "discord-avatar.svg"
    avatar.write_text(avatar_svg(width, height, path), encoding="utf-8")
    render(avatar, BRANDING / "discord-avatar.png", 512, 512)
    avatar.unlink()  # only the PNG is used (Discord takes no SVG)

    big = BRANDING / ".m-agent-logo-1024.png"
    render(logo, big, 1024, 1024)
    icon = Image.open(big).convert("RGBA")
    for target in (BRANDING / "m-agent.ico", ROOT / "niko.ico", ROOT / "nikogreen.ico"):
        icon.save(target, sizes=ICO_SIZES)
    big.unlink()
    print(f"Scribbles traced: {width}x{height}, {path.count('M')} curves")


if __name__ == "__main__":
    main()
